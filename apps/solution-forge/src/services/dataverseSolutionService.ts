  async mergeIntoDeployment(
    targetUniqueName: string,
    sourceSolutionIds: string[],
    onProgress?: (done: number, total: number, current?: string) => void,
  ): Promise<MergeResult> {
    const mode = await powerModeReady
    if (mode !== 'power-platform')
      return mockSolutionService.mergeIntoDeployment(
        targetUniqueName,
        sourceSolutionIds,
        onProgress,
      )

    // Resolve target id + the components already present, so re-merges skip
    // instead of failing.
    const solutions = await this.listSolutions()
    const target = solutions.find((s) => s.uniqueName === targetUniqueName)
    if (!target) throw new Error(`Unknown target solution ${targetUniqueName}`)
    const existing = new Set(
      (await this.listMergeComponents(target.id)).map((c) =>
        c.objectId.toLowerCase(),
      ),
    )

    const queue: SolutionComponentInfo[] = []
    for (const id of sourceSolutionIds) {
      queue.push(...(await this.listMergeComponents(id)))
    }

    // The release may restrict which component types it accepts: an allow-list
    // (empty = all) and an exclude-list applied on top.
    const allowed = target.allowedMergeTypes ?? []
    const excluded = target.excludedMergeTypes ?? []
    const isAllowed = (typeCode: number) =>
      (allowed.length === 0 || allowed.includes(typeCode)) &&
      !excluded.includes(typeCode)

    const result: MergeResult = { added: 0, skipped: 0, excluded: 0, errors: [] }
    // The concrete components actually added in this run — logged to the
    // merge-run row so the history can show what each merge contributed.
    const added: SolutionComponentInfo[] = []
    let done = 0
    for (const component of queue) {
      if (!isAllowed(component.typeCode)) {
        result.excluded++
      } else if (existing.has(component.objectId.toLowerCase())) {
        result.skipped++
      } else {
        try {
          // Carry the source's subcomponent behavior over to the target:
          // 0 = include subcomponents, 1 = do not include, 2 = shell only
          // (signalled by an empty IncludedComponentSettingsValues).
          const doNotIncludeSubcomponents =
            component.rootBehavior === 1 || component.rootBehavior === 2
          const res = await AddSolutionComponentService.AddSolutionComponent(
            component.objectId,
            component.typeCode,
            targetUniqueName,
            false,
            doNotIncludeSubcomponents,
            component.rootBehavior === 2 ? [] : undefined,
          )
          if (res.success) {
            existing.add(component.objectId.toLowerCase())
            added.push(component)
            result.added++
          } else {
            console.warn('[solutions] AddSolutionComponent failed:', res)
            result.errors.push(
              `${component.typeName} ${shortGuid(component.objectId)}: rejected`,
            )
          }
        } catch (err) {
          result.errors.push(
            `${component.typeName} ${shortGuid(component.objectId)}: ${String(err)}`,
          )
        }
      }
      onProgress?.(
        ++done,
        queue.length,
        component.displayName || component.typeName,
      )
    }

    // Log the merge on the source rows' presentation records — the table
    // carries dedicated fields for exactly this.
    if (result.added > 0 || result.skipped > 0) {
      const mergedAt = new Date().toISOString()
      const sourceSolutions = solutions.filter((s) =>
        sourceSolutionIds.includes(s.id),
      )
      for (const source of sourceSolutions) {
        if (!source.recordId) continue
        try {
          await Pro_workingsolutionsService.update(
            source.recordId,
            {
              pro_mergeintodeploymentsolution: true,
              pro_lastmergeintodeploymentsolution: mergedAt,
              pro_deploymentstatus: DEPLOYMENT_STATUS_MERGED,
            } as unknown as Partial<
              Omit<Pro_workingsolutionsBase, 'pro_workingsolutionid'>
            >,
          )
        } catch (err) {
          // Logging must not fail the merge itself.
          console.warn('[solutions] merge log update failed:', err)
        }
      }

      // Append one merge-run history row on the target. The added components
      // ride along as a compact JSON array in a single multiline column
      // (pro_addedcomponents_txt) — no child table to keep the schema lean.
      try {
        await this.logMergeRun(target, sourceSolutions, result, added, mergedAt)
      } catch (err) {
        // History is best-effort — never fail the merge over it.
        console.warn('[solutions] merge-run history write failed:', err)
      }
    }
    return result
  }

  /** Create the pro_mergerun row for one completed merge. */
  private async logMergeRun(
    target: WorkingSolution,
    sourceSolutions: WorkingSolution[],
    result: MergeResult,
    added: SolutionComponentInfo[],
    mergedAt: string,
  ): Promise<void> {
    const components: MergeRunComponent[] = added.map((c) => ({
      t: c.typeName,
      n: c.displayName,
    }))
    const record = {
      pro_name_str: `${target.title} · ${mergedAt.slice(0, 10)}`,
      pro_added_int: result.added,
      pro_skipped_int: result.skipped,
      pro_errors_int: result.errors.length,
      pro_sources_txt: sourceSolutions.map((s) => s.title).join('\n'),
      pro_addedcomponents_txt: components.length
        ? JSON.stringify(components)
        : '',
      // Link back to the target's working-solution record so the history can
      // be queried per release. Skip the bind when the target is untracked.
      ...(target.recordId
        ? {
            'pro_targetsolution_ref@odata.bind': `/pro_workingsolutions(${target.recordId})`,
          }
        : {}),
    } as unknown as Omit<Pro_mergerunsBase, 'pro_mergerunid'>
    const created = await Pro_mergerunsService.create(record)
    if (!created.success) {
      console.warn('[solutions] pro_mergerun create rejected:', created)
      throw new Error('Merge-run history record was rejected.')
    }
  }

